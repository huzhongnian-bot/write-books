async function main() {
  const work = await db.query.sourceWorks.findFirst({
    where: like(sourceWorks.title, "水属性的魔法师%"),
  });
  if (!work) {
    throw new Error("未找到《水属性的魔法师》原作，请先摄取该作品。");
  }

  // 幂等：先删后建
  await db
    .delete(bibleEntries)
    .where(
      and(eq(bibleEntries.workId, work.id), eq(bibleEntries.kind, "relationship"))
    );

  await db.insert(bibleEntries).values(
    RELATIONSHIPS.map((r) => ({
      workId: work.id,
      kind: "relationship" as const,
      name: r.name,
      data: {
        source: r.source,
        target: r.target,
        type: r.type,
        evolution: r.evolution,
      },
      anchors: [],
      confidence: 0.95,
      origin: "user" as const,
      editedByUser: false,
    }))
  );

  console.log(`已导入 ${RELATIONSHIPS.length} 条人物关系（workId=${work.id} 《${work.title}》）`);
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
